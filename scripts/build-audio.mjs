const SRC = path.join(ROOT, "assets/audio/source");
const OUT = path.join(ROOT, "public/audio");
const CEILING_DBTP = -1;
const BITRATE = "128k";
const ONLY = process.argv.includes("--only") ? new Set(process.argv[process.argv.indexOf("--only") + 1].split(",")) : null;

